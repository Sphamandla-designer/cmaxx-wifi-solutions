#!/usr/bin/env node
/**
 * Extracts the customer-facing copy from site/structured-cabling/index.html into
 * content/structured-cabling.md, so the paste-into-Elementor copy source can
 * never drift from the built page.
 *
 *   node tools/extract-copy.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';

const html = readFileSync('site/structured-cabling/index.html', 'utf8');
const main = html.split('<main id="main">')[1].split('</main>')[0];

const decode = s => s
  .replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>')
  .replace(/&nbsp;/g, ' ').replace(/&middot;/g, '·').replace(/&quot;/g, '"');

const inline = s => decode(
  s.replace(/<a[^>]+href="([^"]+)"[^>]*>([\s\S]*?)<\/a>/g,
            (_, href, t) => `[${t.replace(/<[^>]+>/g, '')}](${href})`)
   .replace(/<strong>([\s\S]*?)<\/strong>/g, '**$1**')
   .replace(/<[^>]+>/g, '')
).replace(/\s+/g, ' ').trim();

const out = [
  '# Structured Cabling & Network Infrastructure — page copy',
  '',
  '> Generated from `site/structured-cabling/index.html` by `node tools/extract-copy.mjs`.',
  '> Edit the HTML, then regenerate — do not edit this file by hand.',
  '',
  '**Page name:** Structured Cabling & Network Infrastructure',
  '**Nav label:** Structured Cabling',
  '**Slug:** `/structured-cabling/`',
  '**SEO title:** Structured Cabling & Network Infrastructure Gauteng | CMAXX',
  '**Meta description:** Professional Cat6 and Cat6A structured cabling, data points, PoE cabling, network racks and fibre in Midrand and across Gauteng. Book a site survey.',
  '**Breadcrumb:** Home > Services > Structured Cabling & Network Infrastructure',
  '',
  '---',
  '',
];

// Walk the document in source order.
const TOKEN = /<h([1-4])\b[^>]*>([\s\S]*?)<\/h\1>|<p\b[^>]*>([\s\S]*?)<\/p>|<li\b[^>]*>([\s\S]*?)<\/li>|<summary>([\s\S]*?)<\/summary>|<caption>([\s\S]*?)<\/caption>|<th\b[^>]*>([\s\S]*?)<\/th>|<td\b[^>]*>([\s\S]*?)<\/td>|<span class="eyebrow">([\s\S]*?)<\/span>|<a class="btn[^"]*"[^>]*>([\s\S]*?)<\/a>|<tr\b|<\/table>|<table\b/g;

let inTable = false, row = [], tableRow = 0;
// Emits a markdown row, inserting the header separator after the first row.
const emitRow = () => {
  out.push('| ' + row.join(' | ') + ' |');
  if (tableRow === 0) out.push('| ' + row.map(() => '---').join(' | ') + ' |');
  tableRow += 1;
};

let m;
while ((m = TOKEN.exec(main))) {
  const [raw, hLvl, hTxt, p, li, summ, cap, th, td, eyebrow, btn] = m;

  if (raw.startsWith('<table')) { inTable = true; row = []; tableRow = 0; continue; }
  if (raw === '</table>') {
    if (row.length) emitRow();
    inTable = false; row = []; out.push(''); continue;
  }
  if (raw.startsWith('<tr')) { if (row.length) emitRow(); row = []; continue; }
  if (th !== undefined || td !== undefined) { row.push(inline(th ?? td)); continue; }
  if (cap !== undefined) { out.push(`*${inline(cap)}*`, ''); continue; }

  if (row.length) { emitRow(); row = []; }

  if (eyebrow !== undefined) { out.push(`**${inline(eyebrow).toUpperCase()}**`, ''); continue; }
  if (hLvl) { out.push(`${'#'.repeat(Number(hLvl) + 1)} ${inline(hTxt)}`, ''); continue; }
  if (summ !== undefined) { out.push(`**Q. ${inline(summ)}**`, ''); continue; }
  if (btn !== undefined) { out.push(`\`[CTA] ${inline(btn)}\``, ''); continue; }
  if (li !== undefined) { out.push(`- ${inline(li)}`); continue; }
  if (p !== undefined) {
    const t = inline(p);
    if (t) out.push(t, '');
    continue;
  }
}

// Tidy: collapse runs of blank lines, add a separator after list blocks.
const md = out.join('\n').replace(/\n{3,}/g, '\n\n').replace(/(^- .*(?:\n- .*)*)/gm, '$1\n');
writeFileSync('content/structured-cabling.md', md.trimEnd() + '\n');
console.log(`content/structured-cabling.md written (${md.length} bytes)`);
